INTERVALS_MI = (10, 25, 50)
ROUTE_COLORS = ("#2563eb", "#0d9488", "#c026d3")
MAX_LOAD_LB = 120_000
PLAN_TTL_S = 3 * 3600


# --------------------------------------------------------------------------- input

@dataclass
class TripRequest:
    origin: dict
    destination: dict
    departure: datetime  # UTC
    load_lb: float
    interval_mi: int
    hos: bool


def parse_request(data: dict) -> TripRequest:
    if not isinstance(data, dict):
        raise ValueError("Request body must be a JSON object.")

    try:
        departure = datetime.fromisoformat(str(data.get("departure", "")).replace("Z", "+00:00"))
    except ValueError:
        raise ValueError("Departure must be an ISO date-time, e.g. 2026-11-06T08:00:00Z.") from None
    if departure.tzinfo is None:
        raise ValueError("Departure must include a timezone offset.")
    departure = departure.astimezone(timezone.utc)
    now = datetime.now(timezone.utc)
    if departure < now - timedelta(hours=1):
        raise ValueError("Departure time is in the past.")
    if departure > now + timedelta(days=settings.FORECAST_DAYS - 2):
        raise ValueError(f"Departure must be within the next {settings.FORECAST_DAYS - 2} days (forecast range).")

    try:
        load = float(data.get("load_lb"))
    except (TypeError, ValueError):
        raise ValueError("Load weight must be a number of pounds.") from None
    if not 0 <= load <= MAX_LOAD_LB:
        raise ValueError(f"Load weight must be between 0 and {MAX_LOAD_LB:,} lb.")

    try:
        interval = int(data.get("interval_mi", 25))
    except (TypeError, ValueError):
        interval = -1
    if interval not in INTERVALS_MI:
        raise ValueError("Checkpoint interval must be 10, 25 or 50 miles.")

    origin = providers.resolve_place(data.get("origin"))
    destination = providers.resolve_place(data.get("destination"))
    if haversine_m((origin["lat"], origin["lon"]), (destination["lat"], destination["lon"])) < 1000:
        raise ValueError("Origin and destination are the same place.")

    return TripRequest(origin, destination, departure, load, interval, bool(data.get("hos", True)))


# --------------------------------------------------------------------------- routes

def _bucket(p: LatLon, size: float) -> tuple[int, int]:
    return int(math.floor(p[0] / size)), int(math.floor(p[1] / size))


def overlap(a: RawRoute, b: RawRoute, tol_m: float = 1500) -> float:
    """Share of route `b` that runs within `tol_m` of route `a` (0..1)."""
    size = 0.03
    grid: dict[tuple[int, int], list[LatLon]] = {}
    for p in resample(a.coords, cumulative_distances(a.coords), 750):
        grid.setdefault(_bucket(p, size), []).append(p)
    samples = resample(b.coords, cumulative_distances(b.coords), 4000)
    near = 0
    for p in samples:
        bi, bj = _bucket(p, size)
        if any(
            fast_distance_m(p, q) <= tol_m
            for di in (-1, 0, 1) for dj in (-1, 0, 1)
            for q in grid.get((bi + di, bj + dj), ())
        ):
            near += 1
    return near / len(samples)


def candidate_routes(o: LatLon, d: LatLon, want: int = 3) -> tuple[list[RawRoute], list[str]]:
    """Up to `want` distinct routes. OSRM often returns fewer alternatives than
    asked, so extra options are generated by routing through a detour waypoint
    to each side of the main route's midpoint."""
    warnings: list[str] = []
    found = providers.fetch_routes([o, d], alternatives=want)
    if not found:
        raise ValueError("No drivable route was found between these places.")

    routes: list[RawRoute] = []
    for r in found:
        if all(overlap(x, r) < 0.85 for x in routes):
            routes.append(r)

    main = routes[0]
    straight = haversine_m(o, d)
    mid, _ = interpolate(main.coords, cumulative_distances(main.coords), main.distance_m / 2)
    heading = bearing_deg(o, d)
    for frac in (0.15, 0.3):
        for side in (90, -90):
            if len(routes) >= want:
                break
            via = destination_point(mid, heading + side, straight * frac)
            try:
                options = providers.fetch_routes([o, via, d])
            except providers.ProviderError:
                continue
            for r in options:
                if r.distance_m <= main.distance_m * 1.6 and all(overlap(x, r) < 0.85 for x in routes):
                    routes.append(r)
                    break
    if len(routes) < want:
        warnings.append(f"Only {len(routes)} distinct route(s) exist between these places.")
    return routes[:want], warnings


# --------------------------------------------------------------------------- per-route analysis

def _iso(dt: datetime) -> str:
    return dt.astimezone(timezone.utc).isoformat().replace("+00:00", "Z")


def _checkpoint_marks(total_m: float, interval_mi: int) -> list[float]:
    step = interval_mi * METERS_PER_MILE
    marks = [k * step for k in range(int(total_m // step) + 1)]
    if total_m - marks[-1] > 1:
        marks.append(total_m)
    return marks


@dataclass
class RouteWork:
    raw: RawRoute
    cum: list[float]
    elapsed: list[float]
    drive_s: float
    stops: list
    marks: list[float]
    points: list[LatLon]
    etas: list[datetime]


def prepare_route(raw: RawRoute, trip: TripRequest) -> RouteWork:
    vmax = settings.TRUCK_MAX_SPEED_MPH * 0.44704
    durations = [max(t, dist / vmax) for dist, t in zip(raw.seg_dist_m, raw.seg_dur_s)]
    elapsed, stops = build_timeline(raw.seg_dist_m, durations, HOSRules() if trip.hos else None)
    cum = cumulative_distances(raw.coords)
    marks = _checkpoint_marks(cum[-1], trip.interval_mi)
    points = [interpolate(raw.coords, cum, m)[0] for m in marks]
    etas = [trip.departure + timedelta(seconds=interpolate_value(cum, elapsed, m)) for m in marks]
    return RouteWork(raw, cum, elapsed, sum(durations), stops, marks, points, etas)


def _risk_segments(coords: list[LatLon], cum: list[float], marks: list[float], levels: list[int | None]):
    """Display geometry split at checkpoints and coloured by the segment risk."""
    out: list[dict] = []
    j = 0
    for i in range(len(marks) - 1):
        a, b = marks[i], marks[i + 1]
        known = [x for x in (levels[i], levels[i + 1]) if x is not None]
        level = max(known) if known else None
        pts = [interpolate(coords, cum, a)[0]]
        while j < len(cum) and cum[j] <= a:
            j += 1
        k = j
        while k < len(cum) and cum[k] < b:
            pts.append(coords[k])
            k += 1
        pts.append(interpolate(coords, cum, b)[0])
        if out and out[-1]["level"] == level:
            out[-1]["coords"].extend(pts[1:])
        else:
            out.append({"level": level, "coords": pts})
    for seg in out:
        seg["coords"] = [[round(la, 5), round(lo, 5)] for la, lo in seg["coords"]]
    return out


def summarize_route(work: RouteWork, series_list, trip: TripRequest) -> dict:
    checkpoints, levels = [], []
    for m, (lat, lon), eta, series in zip(work.marks, work.points, work.etas, series_list):
        wind, gust, rain, snow = series.at(eta) if series else (None, None, None, None)
        a = assess(wind, rain, snow, trip.load_lb)
        levels.append(a.level)
        checkpoints.append({
            "mile": round(m / METERS_PER_MILE, 1),
            "lat": round(lat, 5), "lon": round(lon, 5),
            "eta": _iso(eta),
            "wind_mph": wind, "gust_mph": gust, "rain_in": rain, "snow_in": snow,
            "level": a.level, "level_name": a.name, "reasons": a.reasons,
        })

    miles = [0.0] * 5
    unknown = weighted = known_mi = 0.0
    for i in range(len(work.marks) - 1):
        seg_mi = (work.marks[i + 1] - work.marks[i]) / METERS_PER_MILE
        known = [x for x in (levels[i], levels[i + 1]) if x is not None]
        if not known:
            unknown += seg_mi
            continue
        lv = max(known)
        miles[lv] += seg_mi
        weighted += lv * seg_mi
        known_mi += seg_mi

    display = simplify(work.raw.coords, settings.DISPLAY_SIMPLIFY_DEG)
    display_cum = cumulative_distances(display)
    scale = work.cum[-1] / display_cum[-1] if display_cum[-1] else 1.0
    display_cum = [c * scale for c in display_cum]

    stops = []
    for s in work.stops:
        (lat, lon), _ = interpolate(work.raw.coords, work.cum, s.at_m)
        start = trip.departure + timedelta(seconds=s.start_offset_s)
        stops.append({
            "kind": s.kind, "mile": round(s.at_m / METERS_PER_MILE, 1), "lat": round(lat, 5), "lon": round(lon, 5),
            "start": _iso(start), "end": _iso(start + timedelta(seconds=s.duration_s)),
            "hours": s.duration_s / 3600,
        })

    known_levels = [x for x in levels if x is not None]
    max_level = max(known_levels) if known_levels else None
    return {
        "distance_mi": round(work.cum[-1] / METERS_PER_MILE, 1),
        "drive_hours": round(work.drive_s / 3600, 2),
        "total_hours": round(work.elapsed[-1] / 3600, 2),
        "departure": _iso(trip.departure),
        "arrival": _iso(trip.departure + timedelta(seconds=work.elapsed[-1])),
        "miles_by_level": [round(x, 1) for x in miles],
        "unknown_miles": round(unknown, 1),
        "avg_risk": None if not known_mi else round(weighted / known_mi, 3),
        "max_level": max_level,
        "max_level_name": "Unknown" if max_level is None else LEVEL_NAMES[max_level],
        "geometry": [[round(a, 5), round(b, 5)] for a, b in display],
        "risk_segments": _risk_segments(display, display_cum, work.marks, levels),
        "checkpoints": checkpoints,
        "stops": stops,
    }


# --------------------------------------------------------------------------- ranking

def rank_key(r: dict):
    """Brief: fewest Severe miles, then fewest High miles, then lowest average
    risk, then shortest travel time. Any No Travel exposure ranks below every
    route without it (it is worse than Severe)."""
    m = r["miles_by_level"]
    avg = r["avg_risk"] if r["avg_risk"] is not None else 0.0
    return (m[NO_TRAVEL] > 0, round(m[NO_TRAVEL], 1), round(m[3], 1), round(m[2], 1), round(avg, 2), r["total_hours"])


def _fmt_hours(h: float) -> str:
    total = int(round(h * 60))
    return f"{total // 60}h {total % 60:02d}m"


def explain(best: dict, others: list[dict]) -> str:
    if not others:
        return "It is the only available route."
    runner = min(others, key=rank_key)
    b, r = best["miles_by_level"], runner["miles_by_level"]
    name = runner["name"]
    if (b[NO_TRAVEL] > 0) != (r[NO_TRAVEL] > 0) or round(b[NO_TRAVEL], 1) != round(r[NO_TRAVEL], 1):
        return f"It avoids No Travel conditions ({b[NO_TRAVEL]:.0f} mi vs {r[NO_TRAVEL]:.0f} mi on {name})."
    if round(b[3], 1) != round(r[3], 1):
        return f"Fewest Severe-risk miles ({b[3]:.0f} mi vs {r[3]:.0f} mi on {name})."
    if round(b[2], 1) != round(r[2], 1):
        return f"Same Severe exposure, and the fewest High-risk miles ({b[2]:.0f} mi vs {r[2]:.0f} mi on {name})."
    ba, ra = best["avg_risk"] or 0, runner["avg_risk"] or 0
    if round(ba, 2) != round(ra, 2):
        return f"Same Severe and High exposure, and the lowest average risk ({ba:.2f} vs {ra:.2f} on {name})."
    return f"Weather risk is equal, and it is the fastest ({_fmt_hours(best['total_hours'])} vs {_fmt_hours(runner['total_hours'])} on {name})."


# --------------------------------------------------------------------------- entry point

def build_plan(data: dict) -> dict:
    trip = parse_request(data)
    o = (trip.origin["lat"], trip.origin["lon"])
    d = (trip.destination["lat"], trip.destination["lon"])
    raws, warnings = candidate_routes(o, d)
    works = [prepare_route(r, trip) for r in raws]

    # One weather call for every checkpoint of every route.
    all_points = [p for w in works for p in w.points]
    last_eta = max(w.etas[-1] for w in works)
    series = providers.fetch_hourly(all_points, trip.departure, last_eta + timedelta(hours=1))

    routes, i = [], 0
    for w in works:
        n = len(w.points)
        routes.append(summarize_route(w, series[i:i + n], trip))
        i += n

    routes.sort(key=lambda r: r["total_hours"])
    for idx, r in enumerate(routes):
        r["id"] = "ABC"[idx]
        r["name"] = f"Route {r['id']}"
        r["color"] = ROUTE_COLORS[idx]

    best = min(routes, key=rank_key)
    for r in routes:
        r["recommended"] = r is best
        tags = []
        if r["total_hours"] == min(x["total_hours"] for x in routes):
            tags.append("Fastest")
        if r["distance_mi"] == min(x["distance_mi"] for x in routes):
            tags.append("Shortest")
        r["tags"] = tags

    rec_warning = None
    if all(r["miles_by_level"][NO_TRAVEL] > 0 for r in routes):
        rec_warning = ("Every route meets No Travel conditions at this departure time. "
                       "Delay departure and re-check the forecast.")
    if any(r["unknown_miles"] > 0 for r in routes):
        warnings.append("Part of the trip is beyond the forecast range, so it has no weather data.")

    plan_id = uuid.uuid4().hex
    samples = [p for w in works for p in resample(w.raw.coords, w.cum, 10_000)]
    lats = [p[0] for p in samples]
    lons = [p[1] for p in samples]
    cache.set(f"plan:{plan_id}", {
        "bbox": [min(lats), min(lons), max(lats), max(lons)],
        "samples": samples,
        "departure": trip.departure,
    }, PLAN_TTL_S)

    return {
        "plan_id": plan_id,
        "origin": trip.origin,
        "destination": trip.destination,
        "departure": _iso(trip.departure),
        "load_lb": trip.load_lb,
        "interval_mi": trip.interval_mi,
        "hos": trip.hos,
        "routes": routes,
        "recommendation": {
            "route_id": best["id"],
            "reason": explain(best, [r for r in routes if r is not best]),
            "warning": rec_warning,
        },
        "warnings": warnings,
        "level_names": list(LEVEL_NAMES),
    }
